const ASMAUL_INDEX_KEY = 'dzikir_doa_asmaul_index';

/**
 * Gets next Asmaul Husna rotating index each time called,
 * saving the new index to localStorage.
 */
export function getNextAsmaulHusna(): AsmaulHusnaItem {
  try {
    const raw = localStorage.getItem(ASMAUL_INDEX_KEY);
    const prev = raw ? parseInt(raw, 10) : 0;
    const next = (prev + 1) % ASMAUL_HUSNA.length;
    localStorage.setItem(ASMAUL_INDEX_KEY, next.toString());
    return ASMAUL_HUSNA[next];
  } catch {
    return ASMAUL_HUSNA[0];
  }
}

export function getCurrentAsmaulHusna(): AsmaulHusnaItem {
  try {
    const raw = localStorage.getItem(ASMAUL_INDEX_KEY);
    const curr = raw ? parseInt(raw, 10) : 0;
    return ASMAUL_HUSNA[curr % ASMAUL_HUSNA.length];
  } catch {
    return ASMAUL_HUSNA[0];
  }
}
